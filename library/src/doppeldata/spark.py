"""Synthetic datasets generated inside Spark executors: as a DataFrame, or as the files `doppeldata.write` writes.

Each executor imports the same doppeldata the driver runs and builds the engine's plan from the same arguments, so every block it
makes is the block a local run makes, whatever the partitioning. This module imports pyspark and pyarrow, and doppeldata
declares neither, so a job that never touches Spark carries neither.
"""

import dataclasses as dc
import functools
import json
import os
import time
from collections.abc import Iterator
from typing import Any

try:
    import pyarrow as pa
    import pyspark.sql.types as st
    from pyspark.sql import DataFrame
    from pyspark.sql import SparkSession
    from pyspark.sql.pandas.types import from_arrow_schema
except ImportError as error:
    raise ImportError(
        f'doppeldata.spark needs {error.name}, which doppeldata does not install; run it inside PySpark 3.5 or later with '
        'pyarrow 15 or later, or run `pip install pyspark pyarrow`'
    ) from error

from doppeldata import _core
from doppeldata.dataset_generation import EngineArguments
from doppeldata.dataset_generation import WriteChoices
from doppeldata.dataset_generation import destination_of
from doppeldata.dataset_generation import engine_arguments
from doppeldata.errors import WriteFailed
from doppeldata.manifest import Manifest
from doppeldata.profile_format import Profile

# The engine blocks each Spark task generates in turn: 16 blocks of 65,536 rows is 1,048,576 rows. The chunk is a unit of work and
# never of values, so its size moves no value.
CHUNK_BLOCKS = 16

# Arrow types whose arrays Spark 3.5 and 4.x read through mapInArrow with every value kept, besides a timestamp in microseconds, a
# list and a struct of them. A large_string comes back from Spark as a string. `struct_type` refuses a column of any other type.
SPARK_HOLDS = (
    pa.types.is_boolean,
    pa.types.is_signed_integer,
    pa.types.is_float32,
    pa.types.is_float64,
    pa.types.is_string,
    pa.types.is_large_string,
    pa.types.is_date32,
    pa.types.is_decimal128,
)


@dc.dataclass(frozen=True)
class ExecutorPlan:
    """The engine's arguments as the driver resolved them, and its release, which an executor's engine must match."""

    arguments: EngineArguments
    engine_version: str

    def plan(self) -> '_core.Plan':
        if self.engine_version != _core.VERSION:
            raise RuntimeError(
                f'this executor runs doppeldata {_core.VERSION} and the driver {self.engine_version}; install one release on both, '
                'because a dataset is generated by the release that plans it'
            )
        return built_plan(self.arguments)


@functools.lru_cache(maxsize=4)
def built_plan(arguments: EngineArguments) -> '_core.Plan':
    """The engine's plan, built once per executor process for each dataset its tasks generate."""
    return arguments.plan()


@dc.dataclass(frozen=True)
class ChunkBatches:
    """What each Spark task runs for `generate`: the batches of every chunk whose number its partition holds, in order."""

    executor_plan: ExecutorPlan

    def __call__(self, batches: Iterator[Any]) -> Iterator[Any]:
        engine = self.executor_plan.plan()
        for batch in batches:
            for chunk in batch.column(0).to_pylist():
                start = chunk * CHUNK_BLOCKS
                stop = min(start + CHUNK_BLOCKS, engine.block_count)
                yield from pa.RecordBatchReader.from_stream(engine.stream_blocks(start, stop, threads=1))


@dc.dataclass(frozen=True)
class RangeWrites:
    """What each Spark task runs for `write`: the objects of every range whose number its partition holds, yielding one record each."""

    executor_plan: ExecutorPlan
    choices_json: str
    destination: str
    bucket: str | None

    def __call__(self, batches: Iterator[Any]) -> Iterator[Any]:
        ranges = [number for batch in batches for number in batch.column(0).to_pylist()]
        if not ranges:
            return
        engine = self.executor_plan.plan()
        options = engine.write_options(self.choices_json)
        files = engine.write_ranges(options, self.destination, ranges, threads=1, s3_store=s3_store(self.destination, self.bucket))
        records = [json.dumps(record) for record in json.loads(files)]
        yield pa.record_batch([pa.array(records, pa.string())], names=['file'])


def s3_store(destination: str, bucket: str | None) -> dict[str, Any] | None:
    """The S3 store's settings for `destination`, from boto3's chain in this process, or None for a destination not on S3."""
    if bucket is None:
        return None
    from doppeldata.s3_access import s3_store_settings

    return s3_store_settings(destination, bucket)


def executor_plan(profile: Profile, rows: int | None, seed: int) -> tuple[ExecutorPlan, '_core.Plan']:
    """What executors build the plan from, and the plan built on the driver, which refuses an ungenerable profile before a task runs."""
    planned = ExecutorPlan(engine_arguments(profile, rows, seed), _core.VERSION)
    return planned, planned.plan()


def checked_partitions(partitions: int | None, units: int) -> int:
    if partitions is not None and partitions < 1:
        raise ValueError(f'partitions must be 1 or more, not {partitions}')
    return partitions or max(units, 1)


def arrow_struct_type(engine: '_core.Plan') -> Any:
    """The Spark schema of the engine's batches. A column whose values Spark would not hold exactly is refused, naming it."""
    schema = pa.RecordBatchReader.from_stream(engine.stream_blocks(0, 0, threads=1)).schema
    for field in schema:
        if not spark_holds(field.type):
            raise ValueError(
                f'column {field.name!r} is {field.type}, which Spark cannot hold exactly; set its physical_type in the profile to a '
                'type Spark holds, such as int64 for an unsigned integer, timestamp[us] for a timestamp, date32 for a date64, or '
                'list for a large_list'
            )
    return from_arrow_schema(schema, prefer_timestamp_ntz=True)


def spark_holds(data_type: Any) -> bool:
    if pa.types.is_timestamp(data_type):
        return bool(data_type.unit == 'us')
    if pa.types.is_list(data_type):
        return spark_holds(data_type.value_type)
    if pa.types.is_struct(data_type):
        return all(spark_holds(data_type.field(index).type) for index in range(data_type.num_fields))
    return any(holds(data_type) for holds in SPARK_HOLDS)


def struct_type(profile: Profile) -> 'st.StructType':
    """The Spark schema of the DataFrame `generate` returns for `profile`.

    A timestamp with no time zone is a TimestampNTZType, and one with a zone a TimestampType. A column Spark cannot carry with
    every value kept raises ValueError naming it: an unsigned integer, a timestamp in any unit but microseconds, a date64, a
    time32 or time64, or a large_list.
    """
    _, engine = executor_plan(profile, 0, 0)
    return arrow_struct_type(engine)


def generate(spark: SparkSession, profile: Profile, *, rows: int | None = None, seed: int = 0, partitions: int | None = None) -> DataFrame:
    """The dataset as a DataFrame whose rows Spark's executors generate, with the values `doppeldata.generate` returns, in its order.

    Each task generates whole chunks of `CHUNK_BLOCKS` engine blocks through `mapInArrow`, so `partitions`, one per chunk when
    None, changes which task makes a row and never its value. Write it with any Spark writer, partitioned as the run needs.
    Every executor must have the driver's doppeldata release installed.
    """
    planned, engine = executor_plan(profile, rows, seed)
    schema = arrow_struct_type(engine)
    chunks = -(-engine.block_count // CHUNK_BLOCKS)
    numbers = spark.range(chunks, numPartitions=checked_partitions(partitions, chunks))
    return numbers.mapInArrow(ChunkBatches(planned), schema)


def write(
    spark: SparkSession,
    profile: Profile,
    out: str | os.PathLike[str],
    *,
    rows: int | None = None,
    seed: int = 0,
    format: str | None = None,
    file_rows: int | None = None,
    partition_by: list[str] | None = None,
    partition_style: str | None = None,
    writer: dict[str, Any] | None = None,
    replace: bool = False,
    partitions: int | None = None,
) -> Manifest:
    """Write from Spark's executors the files `doppeldata.write` writes with the same arguments, byte for byte, and `_manifest.json`.

    The driver claims `out` as `doppeldata.write` does. Each task writes whole planned files, one per partition value for a
    partitioned range, and returns their records. The driver then stores the manifest from them. `partitions` is one per planned
    range when None. Every executor needs the driver's doppeldata release, and boto3 for an S3 destination, whose credentials
    each executor resolves through its own boto3 chain.

    A failed Spark job raises WriteFailed with code `ranges-unrecorded`, leaving `_manifest.partial.json`, and `replace` then
    deletes every file the run wrote.
    """
    started = time.monotonic()
    destination, _, bucket = destination_of(out)
    choices_json = WriteChoices(format, file_rows, partition_by, partition_style, writer).engine_json(profile)
    planned, engine = executor_plan(profile, rows, seed)
    options = engine.write_options(choices_json)
    ranges = len(json.loads(engine.ranges_json(options)))
    store = s3_store(destination, bucket)
    tasks = checked_partitions(partitions, ranges)
    engine.claim(options, destination, replace=replace, s3_store=store)
    writes = RangeWrites(planned, choices_json, destination, bucket)

    def commit(files_json: str) -> Manifest:
        elapsed_ms = round((time.monotonic() - started) * 1000)
        return Manifest.from_json(engine.commit(options, destination, files_json, tasks=tasks, elapsed_ms=elapsed_ms, s3_store=store))

    try:
        records = spark.range(ranges, numPartitions=tasks).mapInArrow(writes, 'file string').collect()
    except Exception as error:
        try:
            commit('[]')
        except WriteFailed as failed:
            raise failed from error
        raise
    return commit('[' + ','.join(record.file for record in records) + ']')
